pub struct Font {
    tex: Texture2D,
}

const CELL_W: f32 = 6.0;
const CELL_H: f32 = 8.0;

impl Font {
    /// Build the glyph atlas once from the packed bits above.
    pub fn new() -> Self {
        let mut px = vec![0u8; 95 * CELL_W as usize * CELL_H as usize * 4];
        for (i, g) in GLYPHS.iter().enumerate() {
            for (r, row) in g.iter().enumerate() {
                for c in 0..5u32 {
                    if row & (1 << (4 - c)) != 0 {
                        let x = i * CELL_W as usize + c as usize;
                        let y = r;
                        let idx = (y * 95 * CELL_W as usize + x) * 4;
                        px[idx] = 255;
                        px[idx + 1] = 255;
                        px[idx + 2] = 255;
                        px[idx + 3] = 255;
                    }
                }
            }
        }
        let tex = Texture2D::from_rgba8(95 * CELL_W as u16, CELL_H as u16, &px);
        tex.set_filter(FilterMode::Nearest);
        Self { tex }
    }

    /// Draw pixel text at integer-ish position with integer scale. Returns end x.
    pub fn draw(&self, text: &str, x: f32, y: f32, scale: f32, color: Color) -> f32 {
        let mut cx = x;
        for ch in text.chars() {
            let code = (ch as u8).clamp(b' ', b'~');
            let idx = (code - b' ') as usize;
            draw_texture_ex(
                &self.tex,
                cx,
                y,
                color,
                DrawTextureParams {
                    source: Some(Rect::new(idx as f32 * CELL_W, 0.0, CELL_W, CELL_H)),
                    dest_size: Some(vec2(CELL_W * scale, CELL_H * scale)),
                    ..Default::default()
                },
            );
            cx += (CELL_W - 1.0) * scale + scale;
        }
        cx
    }

    pub fn width(&self, text: &str, scale: f32) -> f32 {
        let n = text.chars().count() as f32;
        if n == 0.0 {
            0.0
        } else {
            n * CELL_W * scale - scale
        }
    }

    /// Draw centered at (cx, cy) — cx is the horizontal center.
    pub fn draw_centered(&self, text: &str, cx: f32, y: f32, scale: f32, color: Color) {
        let w = self.width(text, scale);
        self.draw(text, cx - w * 0.5, y, scale, color);
    }
}

impl Default for Font {
    fn default() -> Self {
        Self::new()
    }
}
